const ACCENTS = {
  acute: '...#.',
  tilde: '.###.',
  umlaut: '.#.#.',
};

// Accented characters reuse a base shape and add a mark on row 0.
const ACCENTED = {
  'Á': ['A', 'acute'], 'É': ['E', 'acute'], 'Í': ['I', 'acute'],
  'Ó': ['O', 'acute'], 'Ú': ['U', 'acute'], 'Ñ': ['N', 'tilde'],
  'Ü': ['U', 'umlaut'],
};

/** Every character this font can draw. */
export const CHARS = [...Object.keys(BASE), ...Object.keys(ACCENTED)];

/** Characters missing from the font fall back to this one. */
export const FALLBACK = '?';

/** Returns the 8-row cell for a character, or null when it is unknown. */
export function cellFor(char) {
  if (BASE[char]) return [BLANK, ...BASE[char]];
  const accented = ACCENTED[char];
  if (accented) {
    const [base, mark] = accented;
    return [ACCENTS[mark], ...BASE[base]];
  }
  return null;
}

/**
 * Normalises a string so it can always be drawn: uppercase, and unknown
 * characters swapped for the fallback glyph.
 */
export function normalise(text) {
  return String(text)
    .toUpperCase()
    .split('')
    .map((char) => (cellFor(char) ? char : FALLBACK))
    .join('');
}

/** Width in pixels of a single line of normalised text. */
export function measure(line) {
  if (line.length === 0) return 0;
  return line.length * (CELL_W + GLYPH_SPACING) - GLYPH_SPACING;
}
